/*
 * EXTI 콜백: ISR에서는 "엣지 정보만" 큐로 전달
 * msg = (tick << 1) | level
 * level: 풀다운 기준 pressed=1(SET), released=0(RESET)
 *
 * [PORTFOLIO NOTE]
 * - ISR에 로직(디바운스/판정/모터제어)을 넣으면 지연/우선순위/재진입 문제로 시스템이 불안정해진다.
 * - ISR은 이벤트 캡처 + 큐 전송만 하고,
 *   해석/상태변경은 Task에서 수행하도록 분리했다.
 */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  if (GPIO_Pin != BTN_PIN) return;
  if (btnEdgeQHandle == NULL) return;
  if (osKernelGetState() != osKernelRunning) return;

  uint32_t tick = osKernelGetTickCount();

  /* 외부 풀다운: pressed=SET(1), released=RESET(0) */
  uint32_t level = (HAL_GPIO_ReadPin(BTN_PORT, BTN_PIN) == GPIO_PIN_SET) ? 1u : 0u;

  uint32_t msg = (tick << 1) | (level & 1u);

  /* ISR에서 timeout=0으로만 사용 */
  (void)osMessageQueuePut(btnEdgeQHandle, &msg, 0U, 0U);
}
